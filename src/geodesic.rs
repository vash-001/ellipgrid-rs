//! Exact ellipsoidal Direct & Inverse geodesics (Vincenty + Karney).
//!
//! # The inverse problem
//!
//! [`inverse`] solves for the geodesic between two arbitrary points,
//! returning the distance `s12`, the forward azimuth `azi1`, the reverse
//! azimuth `azi2`, and the reduced length `m12`:
//!
//! 1. **Helmert/Vincenty iteration.** The reduced longitudes are iterated
//!    with the classical Vincenty fixed-point map (`O(f⁴)` series). This
//!    converges quadratically for the overwhelming majority of inputs.
//! 2. **Karney-series evaluation.** Once the iteration has converged, the
//!    distance and reduced length are evaluated with the 6th-order Karney
//!    Fourier series in `ε` (the auxiliary-sphere ellipticity), giving
//!    ≲10⁻⁸ m accuracy instead of Vincenty's ≲0.5 mm.
//! 3. **Newton–Raphson antipodal fallback.** When `|λ₁₂| > π − 10⁻³` or the
//!    Vincenty iteration fails to converge within 64 steps, a damped 2-D
//!    Newton–Raphson solver on `(azi1, s12)` — driven by the direct problem
//!    and started from multiple initial guesses (the spherical solution,
//!    Vincenty's last iterate, and the four cardinal azimuths) — guarantees
//!    convergence for *any* pair of coordinates on Earth, including exactly
//!    antipodal points.
//!
//! [`inverse_vincenty_classic`] exposes the strict `O(f⁴)` Vincenty
//! evaluation (no fallback) for cross-validation.
//!
//! # The direct problem
//!
//! [`direct`] solves for the endpoint and final azimuth given a start, an
//! azimuth, and an arc length. The arc `σ₁₂` on the auxiliary sphere is
//! recovered from the metric length through the same 6th-order series
//! (`s = b·A₁·(σ₁₂ + ΔB₁)`), iterated to machine precision.
//!
//! # Reference baselines
//!
//! The unit tests embed the 20 canonical WGS84 geodesic test cases from
//! GeographicLib (Karney's `GeodTest` gold set), asserting `s12`, `m12`,
//! azimuths, direct endpoints, and the `C4` area swathe `S12`.

use crate::ellipsoid::{normalize_angle, Coord, Ellipsoid};
use core::f64::consts::{FRAC_PI_2, PI};

/// Result of the inverse geodesic problem.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct GeodesicInverseResult {
    /// Geodesic distance (meters).
    pub s12: f64,
    /// Forward azimuth at `p1` (radians, in `(−π, π]`).
    pub azi1: f64,
    /// Reverse azimuth at `p2` (radians, in `(−π, π]`).
    pub azi2: f64,
    /// Reduced length (meters): the separation of two infinitesimally close
    /// geodesics at the endpoints; `m12 ≈ s12` for short geodesics.
    pub m12: f64,
}

/// Result of the direct geodesic problem.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct GeodesicDirectResult {
    /// Latitude of the endpoint (radians).
    pub lat2: f64,
    /// Longitude of the endpoint (radians, in `(−π, π]`).
    pub lon2: f64,
    /// Reverse (final) azimuth at the endpoint (radians, in `(−π, π]`).
    pub azi2: f64,
}

/// Maximum fixed-point iterations for the Vincenty loop.
const VINCENTY_MAX_ITER: u32 = 64;
/// Convergence threshold for the Vincenty longitude iteration (radians).
const VINCENTY_TOL: f64 = 1e-14;
/// Half-width of the near-antipodal guard band: `|λ12| > π − ANTIPODAL_BAND`
/// routes the inverse problem to the Newton fallback.
const ANTIPODAL_BAND: f64 = 1e-3;

// ---------------------------------------------------------------------------
// Karney Fourier series in ε (6th order), coefficient tables from
// GeographicLib v2.x (generated by Maxima; see Geodesic.cpp / C4coeff).
// ---------------------------------------------------------------------------

/// `A1 − 1` as a function of `ε`:
/// `(1−ε)·A1 − 1 = (ε⁶ + 4ε⁴ + 64ε²)/256` in nested form.
#[inline]
fn a1m1f(eps: f64) -> f64 {
    let x = eps * eps;
    let t = (x * x * x + 4.0 * (x * x) + 64.0 * x) / 256.0;
    (t + eps) / (1.0 - eps)
}

/// `A2 − 1` as a function of `ε`:
/// `(1+ε)·A2 − 1 = (−11ε⁶ − 28ε⁴ − 192ε²)/256` in nested form.
#[inline]
fn a2m1f(eps: f64) -> f64 {
    let x = eps * eps;
    let t = (-11.0 * x * x * x - 28.0 * (x * x) - 192.0 * x) / 256.0;
    (t - eps) / (1.0 + eps)
}

/// Coefficients `C1[l]`, `l = 1..=6` — sine series for the reduced length of
/// the auxiliary arc (used for `s12` and `m12`).
fn c1_coeffs(eps: f64) -> [f64; 7] {
    let x = eps * eps;
    let e2 = eps * eps;
    let e3 = e2 * eps;
    let e4 = e2 * e2;
    let e5 = e4 * eps;
    let e6 = e4 * e2;
    let mut c = [0.0; 7];
    c[1] = eps * (-x * x + 6.0 * x - 16.0) / 32.0;
    c[2] = e2 * (-9.0 * x * x + 64.0 * x - 128.0) / 2048.0;
    c[3] = e3 * (9.0 * x - 16.0) / 768.0;
    c[4] = e4 * (3.0 * x - 5.0) / 512.0;
    c[5] = -7.0 * e5 / 1280.0;
    c[6] = -7.0 * e6 / 2048.0;
    c
}

/// Coefficients `C2[l]`, `l = 1..=6` — sine series for the reverse reduced
/// length terms.
fn c2_coeffs(eps: f64) -> [f64; 7] {
    let x = eps * eps;
    let e2 = eps * eps;
    let e3 = e2 * eps;
    let e4 = e2 * e2;
    let e5 = e4 * eps;
    let e6 = e4 * e2;
    let mut c = [0.0; 7];
    c[1] = eps * (x * x + 2.0 * x + 16.0) / 32.0;
    c[2] = e2 * (35.0 * x * x + 64.0 * x + 384.0) / 2048.0;
    c[3] = e3 * (15.0 * x + 80.0) / 768.0;
    c[4] = e4 * (7.0 * x + 35.0) / 512.0;
    c[5] = 63.0 * e5 / 1280.0;
    c[6] = 77.0 * e6 / 2048.0;
    c
}

/// `C4[l]` coefficients, `l = 0..=5` — cosine series for the edge area
/// swathe (Karney's Gauss–Bonnet `C4` series). Each `C4[l]` is
/// `eps^l · Σ_{j=l..5} P[l][j](n)·eps^(j−l)` where the coefficient
/// polynomials `P[l][j]` in the third flattening `n` come from
/// GeographicLib's `C4coeff` table (order 6, generated by Maxima).
fn c4_coeffs(eps: f64, n: f64) -> [f64; 6] {
    let n2 = n * n;
    let n3 = n2 * n;
    let n4 = n3 * n;
    let n5 = n4 * n;
    let x = eps;
    let x2 = x * x;
    let x3 = x2 * x;
    let x4 = x3 * x;
    let x5 = x4 * x;
    let mut c = [0.0; 6];
    // C4[0] = Σ_{j=0..5} P_j(n)·eps^j  (coefficients ascending in eps).
    let p0 = (100.0 * n5 + 208.0 * n4 + 572.0 * n3 + 3432.0 * n2 - 12012.0 * n + 30030.0)
        / 45045.0;
    let p1 = (64.0 * n4 + 624.0 * n3 - 4576.0 * n2 + 6864.0 * n - 3003.0) / 15015.0;
    let p2 = (-10656.0 * n3 + 14144.0 * n2 - 4576.0 * n - 858.0) / 45045.0;
    let p3 = (-224.0 * n2 - 4784.0 * n + 1573.0) / 45045.0;
    let p4 = (1088.0 * n + 156.0) / 45045.0;
    let p5 = 97.0 / 15015.0;
    c[0] = p0 + p1 * x + p2 * x2 + p3 * x3 + p4 * x4 + p5 * x5;
    // C4[1] = eps·Σ_{j=1..5} P_j(n)·eps^(j-1).
    let q1 = (-64.0 * n4 - 624.0 * n3 + 4576.0 * n2 - 6864.0 * n + 3003.0) / 135135.0;
    let q2 = (5952.0 * n3 - 11648.0 * n2 + 9152.0 * n - 2574.0) / 135135.0;
    let q3 = (5792.0 * n2 + 1040.0 * n - 1287.0) / 135135.0;
    let q4 = (-2944.0 * n + 468.0) / 135135.0;
    let q5 = 1.0 / 9009.0;
    c[1] = x * (q1 + q2 * x + q3 * x2 + q4 * x3 + q5 * x4);
    // C4[2] = eps²·Σ_{j=2..5} P_j(n)·eps^(j-2).
    let r2 = (-1440.0 * n3 + 4160.0 * n2 - 4576.0 * n + 1716.0) / 225225.0;
    let r3 = (-8448.0 * n2 + 4992.0 * n - 1144.0) / 225225.0;
    let r4 = (1856.0 * n - 936.0) / 225225.0;
    let r5 = 8.0 / 10725.0;
    c[2] = x2 * (r2 + r3 * x + r4 * x2 + r5 * x3);
    // C4[3] = eps³·Σ_{j=3..5} P_j(n)·eps^(j-3).
    let s3 = (3584.0 * n2 - 3328.0 * n + 1144.0) / 315315.0;
    let s4 = (1024.0 * n - 208.0) / 105105.0;
    let s5 = -136.0 / 63063.0;
    c[3] = x3 * (s3 + s4 * x + s5 * x2);
    // C4[4] = eps⁴·(P₄(n) + P₅(n)·eps).
    let t4 = (-2560.0 * n + 832.0) / 405405.0;
    let t5 = -128.0 / 135135.0;
    c[4] = x4 * (t4 + t5 * x);
    // C4[5] = eps⁵·P₅(n).
    c[5] = x5 * (128.0 / 99099.0);
    c
}

pub(crate) fn reduced_sc_pub(e: &Ellipsoid, phi: f64) -> (f64, f64) {
    reduced_sc(e, phi)
}
pub(crate) fn epsilon_from_calp0_pub(e: &Ellipsoid, calp0: f64) -> f64 {
    epsilon_from_calp0(e, calp0)
}
pub(crate) fn a1m1f_pub(eps: f64) -> f64 {
    a1m1f(eps)
}
pub(crate) fn c1_coeffs_pub(eps: f64) -> [f64; 7] {
    c1_coeffs(eps)
}
pub(crate) fn sincos_series_sin_pub(c: &[f64; 7], sinx: f64, cosx: f64) -> f64 {
    sincos_series_sin(c, sinx, cosx)
}

/// Clenshaw summation of the sine series `Σ_{l=1..6} c[l]·sin(2l·x)`
/// (`c[0]` unused).
fn sincos_series_sin(c: &[f64; 7], sinx: f64, cosx: f64) -> f64 {
    let ar = 2.0 * (cosx - sinx) * (cosx + sinx); // 2·cos(2x)
    let mut u0 = 0.0;
    let mut u1 = 0.0;
    for idx in (1..=6).rev() {
        let u = ar * u0 - u1 + c[idx];
        u1 = u0;
        u0 = u;
    }
    2.0 * sinx * cosx * u0 // sin(2x)·y0
}

/// Clenshaw summation of the cosine series `Σ_{l=0..5} c[l]·cos((2l+1)·x)`.
fn sincos_series_cos(c: &[f64; 6], sinx: f64, cosx: f64) -> f64 {
    let ar = 2.0 * (cosx - sinx) * (cosx + sinx); // 2·cos(2x)
    let mut u0 = 0.0;
    let mut u1 = 0.0;
    // Consume c[5]..c[0]: matches the GeographicLib pointer walk.
    let u = ar * u0 - u1 + c[5];
    u1 = u0;
    u0 = u;
    for idx in (0..=4).rev() {
        let u = ar * u0 - u1 + c[idx];
        u1 = u0;
        u0 = u;
    }
    cosx * (u0 - u1)
}

// ---------------------------------------------------------------------------
// Auxiliary-sphere quantities shared by all solvers.
// ---------------------------------------------------------------------------

/// `(sin β, cos β)` of the reduced latitude at geodetic latitude `phi`,
/// normalized to unit length so that the pair can be used directly as the
/// sine/cosine of the auxiliary-sphere angle.
#[inline]
fn reduced_sc(e: &Ellipsoid, phi: f64) -> (f64, f64) {
    let sbet = e.f1 * phi.sin();
    let cbet = phi.cos();
    let h = sbet.hypot(cbet);
    (sbet / h, cbet / h)
}

/// `ε` from `cos α₀` (the azimuth at the equator crossing):
/// `k² = cos²α₀·e'²`, `ε = k² / (2(1 + √(1+k²)) + k²)`.
#[inline]
fn epsilon_from_calp0(e: &Ellipsoid, calp0: f64) -> f64 {
    let k2 = calp0 * calp0 * e.ep2;
    k2 / (2.0 * (1.0 + (1.0 + k2).sqrt()) + k2)
}

/// The Clairaut pair: `sin α₀ = sin α₁·cos β₁` and
/// `cos α₀ = √(cos²α₁ + sin²α₁·sin²β₁) = √(1 − sin²α₀)`.
#[inline]
fn clairaut(sbet1: f64, cbet1: f64, salp1: f64, calp1: f64) -> (f64, f64) {
    let salp0 = salp1 * cbet1;
    let calp0 = (calp1 * calp1 + salp1 * salp1 * sbet1 * sbet1).sqrt();
    (salp0, calp0)
}

/// Evaluates `s12` and `m12` from converged auxiliary-sphere data using the
/// 6th-order Karney series (GeographicLib formulas):
///
/// * `s12 = b·A₁·(σ₁₂ + ΔB₁)`
/// * `m12 = b·[dn₂·(cosσ₁·sinσ₂) − dn₁·(sinσ₁·cosσ₂) − cosσ₁·cosσ₂·J₁₂]`
///
/// with `J₁₂ = (A₁−A₂)·σ₁₂ + A₁·ΔB₁ − A₂·ΔB₂` and
/// `dnᵢ = √(1 + e'²·sin²βᵢ)`.
#[allow(clippy::too_many_arguments)]
fn karney_evaluate(
    e: &Ellipsoid,
    sbet1: f64,
    cbet1: f64,
    sbet2: f64,
    cbet2: f64,
    salp1: f64,
    calp1: f64,
    _salp2: f64,
    calp2: f64,
    sigma12: f64,
) -> (f64, f64) {
    let (_salp0, calp0) = clairaut(sbet1, cbet1, salp1, calp1);
    let eps = epsilon_from_calp0(e, calp0);
    let a1 = 1.0 + a1m1f(eps);
    let a2 = 1.0 + a2m1f(eps);
    let m0 = a1 - a2;
    let c1 = c1_coeffs(eps);
    let c2 = c2_coeffs(eps);
    // Normalized node-relative arc components:
    // sinσᵢ = sinβᵢ/cosα₀, cosσᵢ = cosαᵢ·cosβᵢ/cosα₀.
    let ssig1 = sbet1 / calp0;
    let csig1 = calp1 * cbet1 / calp0;
    let ssig2 = sbet2 / calp0;
    let csig2 = calp2 * cbet2 / calp0;
    let b1 = sincos_series_sin(&c1, ssig2, csig2) - sincos_series_sin(&c1, ssig1, csig1);
    let s12 = e.b * a1 * (sigma12 + b1);
    let b2 = sincos_series_sin(&c2, ssig2, csig2) - sincos_series_sin(&c2, ssig1, csig1);
    let j12 = m0 * sigma12 + a1 * b1 - a2 * b2;
    let dn1 = (1.0 + e.ep2 * sbet1 * sbet1).sqrt();
    let dn2 = (1.0 + e.ep2 * sbet2 * sbet2).sqrt();
    let m12 = e.b * (dn2 * csig1 * ssig2 - dn1 * ssig1 * csig2 - csig1 * csig2 * j12);
    (s12, m12)
}

