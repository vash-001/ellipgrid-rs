/// Solves the direct geodesic problem: given `p1`, an initial azimuth and a
/// distance, returns the endpoint and the final azimuth.
///
/// The auxiliary arc is recovered from the metric length via the 6th-order
/// Karney series fixed point, then mapped back through the auxiliary sphere.
pub fn direct(e: &Ellipsoid, p1: Coord, azi1: f64, s12: f64) -> GeodesicDirectResult {
    if s12 <= 0.0 {
        return GeodesicDirectResult {
            lat2: p1.lat,
            lon2: normalize_angle(p1.lon),
            azi2: normalize_angle(azi1),
        };
    }
    let (sbet1, cbet1) = reduced_sc(e, p1.lat);
    let salp1 = azi1.sin();
    let calp1 = azi1.cos();
    let salp0 = salp1 * cbet1; // Clairaut constant K
    let calp0 = (calp1 * calp1 + salp1 * salp1 * sbet1 * sbet1).sqrt();
    let eps = epsilon_from_calp0(e, calp0);
    let a1 = 1.0 + a1m1f(eps);
    let c1 = c1_coeffs(eps);
    let sigma1 = sbet1.atan2(calp1 * cbet1);
    let (ss1, cs1) = sigma1.sin_cos();

    // Fixed point: σ12 = s/(b·A1) − (S(σ1+σ12) − S(σ1)).
    let mut sigma12 = s12 / (e.b * a1);
    for _ in 0..24 {
        let sigma2 = sigma1 + sigma12;
        let (ss2, cs2) = sigma2.sin_cos();
        let b1 = sincos_series_sin(&c1, ss2, cs2) - sincos_series_sin(&c1, ss1, cs1);
        let next = s12 / (e.b * a1) - b1;
        if (next - sigma12).abs() < 1e-15 {
            sigma12 = next;
            break;
        }
        sigma12 = next;
    }

    // Spherical geometry on the auxiliary sphere: move from P1 by arc σ12
    // with azimuth α1.
    let (sin_sig12, cos_sig12) = sigma12.sin_cos();
    let sbet2 = sbet1 * cos_sig12 + cbet1 * sin_sig12 * calp1;
    let cbet2 = (cbet1 * cos_sig12 - sbet1 * sin_sig12 * calp1).hypot(sin_sig12 * salp1);
    let cbet2 = cbet2.max(1e-300);
    let lat2 = sbet2.atan2(e.f1 * cbet2);
    // Auxiliary longitude difference from P1 to P2:
    let omg12 = (sin_sig12 * salp1).atan2(cbet1 * cos_sig12 - sbet1 * sin_sig12 * calp1);
    // Ellipsoidal longitude (Vincenty correction at the arc midpoint):
    let cos2_alpha = 1.0 - salp0 * salp0;
    let cos2_sigma_m = if cos2_alpha == 0.0 {
        0.0
    } else {
        (2.0 * sigma1 + sigma12).cos()
    };
    let c = e.f / 16.0 * cos2_alpha * (4.0 + e.f * (4.0 - 3.0 * cos2_alpha));
    let lam12 = omg12
        - (1.0 - c) * e.f * salp0
            * (sigma12
                + c * sin_sig12
                    * (cos2_sigma_m + c * cos_sig12 * (-1.0 + 2.0 * cos2_sigma_m * cos2_sigma_m)));
    let lon2 = normalize_angle(p1.lon + lam12);
    // Final azimuth: α2 = atan2(sin α₀, −sinβ₁·sinσ12 + cosβ₁·cosσ12·cosα1)
    let azi2 = normalize_angle(salp0.atan2(-sbet1 * sin_sig12 + cbet1 * cos_sig12 * calp1));
    GeodesicDirectResult { lat2, lon2, azi2 }
}

// ---------------------------------------------------------------------------
// Edge swathe (C4 area machinery), used by the polygon module.
// ---------------------------------------------------------------------------

/// The signed area swathe `S12` of a single geodesic edge (m²), evaluated
/// with Karney's `C4` series:
///
/// `S12 = A4·(B4(σ2) − B4(σ1)) + R_A²·(α2 − α1)`,
///
/// with `A4 = a²·cos α₀·sin α₀·e²`. Summing `S12` over a closed geodesic
/// polygon yields the enclosed area (up to orientation/antimeridian fix-ups
/// handled by [`crate::polygon`]).
pub fn geodesic_edge_swathe(e: &Ellipsoid, p1: Coord, p2: Coord) -> f64 {
    let lam12 = normalize_angle(p2.lon - p1.lon);
    let (sbet1, cbet1) = reduced_sc(e, p1.lat);
    let (sbet2, cbet2) = reduced_sc(e, p2.lat);

    // Equatorial edge: A4 = 0 and α2 = α1, so S12 = 0.
    if sbet1 == 0.0 && sbet2 == 0.0 && cbet1 > 0.0 && cbet2 > 0.0 {
        return 0.0;
    }

    let st = vincenty_inverse_iterate(e, sbet1, cbet1, sbet2, cbet2, lam12);
    let salp1 = st.salp1;
    let calp1 = st.calp1;
    let salp2 = st.salp2;
    let calp2 = st.calp2;
    let (salp0, calp0) = (st.salp0, st.calp0);

    // alp12 = α2 − α1 with the stable half-angle form when applicable.
    let (somg12, comg12) = st.omg12.sin_cos();
    let alp12 = if comg12 > -0.7071 && sbet2 - sbet1 < 1.75 {
        let domg12 = 1.0 + comg12;
        let dbet1 = 1.0 + cbet1;
        let dbet2 = 1.0 + cbet2;
        2.0 * (somg12 * (sbet1 * dbet2 + sbet2 * dbet1))
            .atan2(domg12 * (sbet1 * sbet2 + dbet1 * dbet2))
    } else {
        let salp12 = salp2 * calp1 - calp2 * salp1;
        let calp12 = calp2 * calp1 + salp2 * salp1;
        if salp12 == 0.0 && calp12 < 0.0 {
            PI
        } else {
            salp12.atan2(calp12)
        }
    };

    if calp0 == 0.0 || salp0 == 0.0 {
        return e.c2 * alp12;
    }
    let a4 = e.a * e.a * calp0 * salp0 * e.e2;
    let eps = epsilon_from_calp0(e, calp0);
    let c4 = c4_coeffs(eps, e.n);
    let sigma1 = sbet1.atan2(calp1 * cbet1);
    let sigma2 = sbet2.atan2(calp2 * cbet2);
    let b41 = sincos_series_cos(&c4, sigma1.sin(), sigma1.cos());
    let b42 = sincos_series_cos(&c4, sigma2.sin(), sigma2.cos());
    a4 * (b42 - b41) + e.c2 * alp12
}

