/// Residual of the shooting equations: `(Δφ, Δλ)` between the endpoint of
/// the trial geodesic and the target.
fn residual(e: &Ellipsoid, p1: Coord, target: Coord, azi: f64, s: f64) -> (f64, f64) {
    let d = direct(e, p1, azi, s);
    (d.lat2 - target.lat, normalize_angle(d.lon2 - target.lon))
}

/// Damped multi-start Newton–Raphson on `(azi1, s12)`.
fn robust_inverse(
    e: &Ellipsoid,
    p1: Coord,
    p2: Coord,
    vincenty_hint: &VincentyState,
) -> GeodesicInverseResult {
    let lam12 = normalize_angle(p2.lon - p1.lon);
    let phi1 = p1.lat;
    let phi2 = p2.lat;

    // Spherical great-circle initial guess.
    let cos_sig = phi1.sin() * phi2.sin() + phi1.cos() * phi2.cos() * lam12.cos();
    let sig_sph = cos_sig.clamp(-1.0, 1.0).acos();
    let azi_sph = (lam12.sin() * phi2.cos())
        .atan2(phi1.cos() * phi2.sin() - phi1.sin() * phi2.cos() * lam12.cos());
    let s_sph = sig_sph * 0.5 * (e.a + e.b);
    // Vincenty hint: azimuth from its last auxiliary longitude, arc scaled.
    let (sbet1, cbet1) = reduced_sc(e, phi1);
    let (sbet2, cbet2) = reduced_sc(e, phi2);
    let hint_azi = vincenty_hint.salp1.atan2(vincenty_hint.calp1);
    let hint_s = vincenty_hint.sigma12.max(1e-9) * 0.5 * (e.a + e.b);
    // Meridional and equatorial half-perimeters as cardinal initial arcs.
    let s_meridian_half = 2.0 * e.meridian_arc(FRAC_PI_2);
    let s_equator_half = PI * e.a;

    let starts: [(f64, f64); 8] = [
        (azi_sph, s_sph),
        (hint_azi, hint_s),
        (0.0, s_meridian_half),
        (PI, s_meridian_half),
        (FRAC_PI_2, s_equator_half),
        (-FRAC_PI_2, s_equator_half),
        (azi_sph, s_meridian_half),
        (hint_azi, s_equator_half),
    ];

    // Collect every converging solution and keep the *shortest* arc: the
    // shooting equations have many solutions (geodesics that reach the
    // target the long way around, including full extra loops past exactly
    // antipodal targets), and only the minimum-s one is the shortest
    // geodesic.
    let mut best: Option<(f64, f64, f64, f64)> = None; // (azi, s, azi2, residual)
    for (azi0, s0) in starts {
        if let Some((azi, s, azi2, res)) = newton_solve(e, p1, p2, azi0, s0) {
            let better = match best {
                None => true,
                Some((_, s_b, _, res_b)) => s < s_b - 1.0 || (res < res_b && (s_b - s).abs() <= 1.0),
            };
            if better {
                best = Some((azi, s, azi2, res));
            }
        }
    }

    if let Some((azi1, s12, azi2, _)) = best {
        let azi1 = normalize_angle(azi1);
        let azi2 = normalize_angle(azi2);
        let salp1 = azi1.sin();
        let calp1 = azi1.cos();
        let salp2 = azi2.sin();
        let calp2 = azi2.cos();
        // Recover σ12 by inverting the s12 series (same fixed point as direct).
        let (_salp0, calp0) = clairaut(sbet1, cbet1, salp1, calp1);
        let eps = epsilon_from_calp0(e, calp0);
        let a1 = 1.0 + a1m1f(eps);
        let c1 = c1_coeffs(eps);
        let sigma1 = sbet1.atan2(calp1 * cbet1);
        let (ss1, cs1) = sigma1.sin_cos();
        let mut sigma12 = s12 / (e.b * a1);
        for _ in 0..16 {
            let sigma2 = sigma1 + sigma12;
            let (ss2, cs2) = sigma2.sin_cos();
            let b1 = sincos_series_sin(&c1, ss2, cs2) - sincos_series_sin(&c1, ss1, cs1);
            let next = s12 / (e.b * a1) - b1;
            if (next - sigma12).abs() < 1e-15 {
                sigma12 = next;
                break;
            }
            sigma12 = next;
        }
        let (_, m12) = karney_evaluate(
            e, sbet1, cbet1, sbet2, cbet2, salp1, calp1, salp2, calp2, sigma12,
        );
        return GeodesicInverseResult { s12, azi1, azi2, m12 };
    }

    // Last resort: return Vincenty's (possibly non-converged) estimate.
    let st = vincenty_inverse_iterate(e, sbet1, cbet1, sbet2, cbet2, lam12);
    let azi1 = normalize_angle(st.salp1.atan2(st.calp1));
    let azi2 = normalize_angle(st.salp2.atan2(st.calp2));
    let (s12, m12) = karney_evaluate(
        e, sbet1, cbet1, sbet2, cbet2, st.salp1, st.calp1, st.salp2, st.calp2, st.sigma12,
    );
    GeodesicInverseResult { s12: s12.abs(), azi1, azi2, m12: m12.abs() }
}

/// Damped 2-D Newton–Raphson on `(azi, s)` with a numerically differentiated
/// Jacobian and Levenberg-style step control.
fn newton_solve(
    e: &Ellipsoid,
    p1: Coord,
    target: Coord,
    azi0: f64,
    s0: f64,
) -> Option<(f64, f64, f64, f64)> {
    let mut azi = normalize_angle(azi0);
    let mut s = s0.max(1.0);
    let mut f = residual(e, p1, target, azi, s);
    let norm = |f: (f64, f64)| (f.0 * f.0 + f.1 * f.1).sqrt();
    let mut best_norm = norm(f);
    let mut damping = 1.0f64;
    for _ in 0..60 {
        if best_norm < 1e-13 {
            let d = direct(e, p1, azi, s);
            return Some((azi, s, d.azi2, best_norm));
        }
        // Numeric Jacobian (central differences).
        let ha = 1e-7;
        let hs = (s * 1e-7).max(1e-6);
        let f_a_plus = residual(e, p1, target, azi + ha, s);
        let f_a_minus = residual(e, p1, target, azi - ha, s);
        let f_s_plus = residual(e, p1, target, azi, s + hs);
        let f_s_minus = residual(e, p1, target, azi, (s - hs).max(0.0));
        let j11 = (f_a_plus.0 - f_a_minus.0) / (2.0 * ha);
        let j21 = (f_a_plus.1 - f_a_minus.1) / (2.0 * ha);
        let j12 = (f_s_plus.0 - f_s_minus.0) / (2.0 * hs);
        let j22 = (f_s_plus.1 - f_s_minus.1) / (2.0 * hs);
        // Solve J·step = −f via Cramer's rule.
        let det = j11 * j22 - j12 * j21;
        let (step_a, step_s) = if det.abs() > 1e-30 {
            ((-f.0 * j22 + f.1 * j12) / det, (-j11 * f.1 + j21 * f.0) / det)
        } else {
            // Singular Jacobian (cut locus): take a damped gradient step.
            let g_a = -(j11 * f.0 + j21 * f.1);
            let g_s = -(j12 * f.0 + j22 * f.1);
            (1e-7 * g_a, 1e-7 * g_s * s.max(1.0))
        };
        // Levenberg-style backtracking.
        let mut accepted = false;
        for _ in 0..30 {
            let trial_azi = normalize_angle(azi + damping * step_a);
            let trial_s = (s + damping * step_s).max(0.0);
            let f_trial = residual(e, p1, target, trial_azi, trial_s);
            let n_trial = norm(f_trial);
            if n_trial.is_finite() && n_trial < best_norm {
                azi = trial_azi;
                s = trial_s;
                f = f_trial;
                best_norm = n_trial;
                damping = (damping * 2.0).min(1.0);
                accepted = true;
                break;
            }
            damping *= 0.5;
            if damping < 1e-12 {
                break;
            }
        }
        if !accepted {
            return None; // stalled: try the next multi-start
        }
    }
    if best_norm < 1e-13 {
        let d = direct(e, p1, azi, s);
        return Some((azi, s, d.azi2, best_norm));
    }
    None
}

