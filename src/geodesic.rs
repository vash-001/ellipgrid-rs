// Vincenty inverse iteration (primary solver).
// ---------------------------------------------------------------------------

/// Raw converged state of the Vincenty inverse iteration.
#[derive(Debug, Clone, Copy)]
struct VincentyState {
    /// Total auxiliary arc `σ₁₂` (radians).
    sigma12: f64,
    /// Clairaut constant `K = cos β·sin α = sin α₀` and `cos α₀ = √(1−K²)`.
    salp0: f64,
    calp0: f64,
    /// Sine/cosine of the endpoint azimuth α₁ (unit-normalized).
    salp1: f64,
    calp1: f64,
    /// Sine/cosine of the endpoint azimuth α₂ (unit-normalized).
    salp2: f64,
    calp2: f64,
    /// Converged auxiliary longitude difference `ω₁₂` (radians).
    omg12: f64,
    /// Whether the iteration converged.
    converged: bool,
}

/// Vincenty fixed-point iteration for the inverse problem.
fn vincenty_inverse_iterate(
    e: &Ellipsoid,
    sbet1: f64,
    cbet1: f64,
    sbet2: f64,
    cbet2: f64,
    lam12: f64,
) -> VincentyState {
    let mut lam = lam12;
    let mut state = VincentyState {
        sigma12: 0.0,
        salp0: 0.0,
        calp0: 1.0,
        salp1: 0.0,
        calp1: 1.0,
        salp2: 0.0,
        calp2: 1.0,
        omg12: lam12,
        converged: false,
    };
    for _ in 0..VINCENTY_MAX_ITER {
        let (slam, clam) = lam.sin_cos();
        let ds1 = cbet2 * slam;
        let ds2 = cbet1 * sbet2 - sbet1 * cbet2 * clam;
        let sin_sigma = (ds1 * ds1 + ds2 * ds2).sqrt();
        let cos_sigma = sbet1 * sbet2 + cbet1 * cbet2 * clam;
        let sigma = sin_sigma.atan2(cos_sigma);
        if !sigma.is_finite() {
            return state;
        }
        let sin_alpha = if sin_sigma == 0.0 {
            0.0
        } else {
            cbet1 * cbet2 * slam / sin_sigma
        };
        let cos2_alpha = 1.0 - sin_alpha * sin_alpha;
        let cos2_sigma_m = if cos2_alpha == 0.0 {
            0.0 // equatorial geodesic: undefined, take 0
        } else {
            cos_sigma - 2.0 * sbet1 * sbet2 / cos2_alpha
        };
        let c = e.f / 16.0 * cos2_alpha * (4.0 + e.f * (4.0 - 3.0 * cos2_alpha));
        let lam_new = lam12
            + (1.0 - c) * e.f * sin_alpha
                * (sigma
                    + c * sin_sigma
                        * (cos2_sigma_m
                            + c * cos_sigma * (-1.0 + 2.0 * cos2_sigma_m * cos2_sigma_m)));
        if !lam_new.is_finite() || lam_new.abs() > PI + 1.0 {
            return state; // diverged
        }
        state.sigma12 = sigma;
        state.salp0 = sin_alpha; // = K, the Clairaut constant
        state.calp0 = cos2_alpha.sqrt();
        // Endpoint azimuths (unit-normalized): the hypotenuse of each
        // azimuth triangle is sinσ.
        state.salp1 = ds1 / sin_sigma;
        state.calp1 = ds2 / sin_sigma;
        state.salp2 = cbet1 * slam / sin_sigma;
        state.calp2 = (-sbet1 * cbet2 + cbet1 * sbet2 * clam) / sin_sigma;
        state.omg12 = lam_new;
        if (lam_new - lam).abs() < VINCENTY_TOL {
            state.converged = true;
            return state;
        }
        lam = lam_new;
    }
    state
}

/// Solves the inverse problem with the strict `O(f⁴)` Vincenty evaluation
/// (`s12 = b·A·(σ − Δσ)`). No antipodal fallback; `None` when the iteration
/// does not converge. Retained for cross-validation against the default
/// Karney-series evaluation.
pub fn inverse_vincenty_classic(
    e: &Ellipsoid,
    p1: Coord,
    p2: Coord,
) -> Option<GeodesicInverseResult> {
    let lam12 = normalize_angle(p2.lon - p1.lon);
    let (sbet1, cbet1) = reduced_sc(e, p1.lat);
    let (sbet2, cbet2) = reduced_sc(e, p2.lat);

    // Equatorial special case (both endpoints on the equator).
    if sbet1 == 0.0 && sbet2 == 0.0 && cbet1 > 0.0 && cbet2 > 0.0 {
        let s12 = e.a * lam12.abs();
        let azi = if lam12 >= 0.0 { FRAC_PI_2 } else { -FRAC_PI_2 };
        let m12 = e.b * (lam12.abs() / e.f1).sin();
        return Some(GeodesicInverseResult { s12, azi1: azi, azi2: azi, m12 });
    }

    let st = vincenty_inverse_iterate(e, sbet1, cbet1, sbet2, cbet2, lam12);
    if !st.converged {
        return None;
    }
    let azi1 = normalize_angle(st.salp1.atan2(st.calp1));
    let azi2 = normalize_angle(st.salp2.atan2(st.calp2));
    let cos2_alpha = 1.0 - st.salp0 * st.salp0;
    let u2 = cos2_alpha * e.ep2;
    let a = 1.0 + u2 / 16384.0 * (4096.0 + u2 * (-768.0 + u2 * (320.0 - 175.0 * u2)));
    let b = u2 / 1024.0 * (256.0 + u2 * (-128.0 + u2 * (74.0 - 47.0 * u2)));
    let (ssig, csig) = st.sigma12.sin_cos();
    let _ = st.salp1;
    let cos2_sigma_m = if cos2_alpha == 0.0 {
        0.0
    } else {
        csig - 2.0 * sbet1 * sbet2 / cos2_alpha
    };
    let delta_sigma = b
        * ssig
        * (cos2_sigma_m
            + b / 4.0
                * (csig * (-1.0 + 2.0 * cos2_sigma_m * cos2_sigma_m)
                    - b / 6.0 * cos2_sigma_m
                        * (-3.0 + 4.0 * ssig * ssig)
                        * (-3.0 + 4.0 * cos2_sigma_m * cos2_sigma_m)));
    let s12 = e.b * a * (st.sigma12 - delta_sigma);
    // The reduced length always uses the more accurate Karney evaluation.
    let (_, m12) = karney_evaluate(
        e, sbet1, cbet1, sbet2, cbet2, st.salp1, st.calp1, st.salp2, st.calp2, st.sigma12,
    );
    Some(GeodesicInverseResult {
        s12,
        azi1: normalize_angle(azi1),
        azi2,
        m12,
    })
}

/// Full inverse geodesic solver: Vincenty iteration + Karney-series
/// evaluation + guaranteed Newton–Raphson antipodal fallback.
///
/// Guarantees a solution (the shortest geodesic) for any pair of coordinates
/// on the ellipsoid, including exactly antipodal points.
pub fn inverse(e: &Ellipsoid, p1: Coord, p2: Coord) -> GeodesicInverseResult {
    let lam12 = normalize_angle(p2.lon - p1.lon);
    let (sbet1, cbet1) = reduced_sc(e, p1.lat);
    let (sbet2, cbet2) = reduced_sc(e, p2.lat);

    // Coincident points.
    if p1.lat == p2.lat && lam12 == 0.0 {
        return GeodesicInverseResult { s12: 0.0, azi1: 0.0, azi2: 0.0, m12: 0.0 };
    }

    // Equatorial special case.
    if sbet1 == 0.0 && sbet2 == 0.0 && cbet1 > 0.0 && cbet2 > 0.0 {
        let s12 = e.a * lam12.abs();
        let azi = if lam12 >= 0.0 { FRAC_PI_2 } else { -FRAC_PI_2 };
        let m12 = e.b * (lam12.abs() / e.f1).sin();
        return GeodesicInverseResult { s12, azi1: azi, azi2: azi, m12 };
    }

    let st = vincenty_inverse_iterate(e, sbet1, cbet1, sbet2, cbet2, lam12);
    let near_antipodal = lam12.abs() > PI - ANTIPODAL_BAND;

    if st.converged && !near_antipodal {
        let azi1 = normalize_angle(st.salp1.atan2(st.calp1));
        let azi2 = normalize_angle(st.salp2.atan2(st.calp2));
        let (s12, m12) = karney_evaluate(
            e, sbet1, cbet1, sbet2, cbet2, st.salp1, st.calp1, st.salp2, st.calp2, st.sigma12,
        );
        if s12 >= 0.0 {
            return GeodesicInverseResult { s12, azi1, azi2, m12 };
        }
    }

    // Newton–Raphson fallback (near-antipodal or Vincenty failure).
    robust_inverse(e, p1, p2, &st)
}

